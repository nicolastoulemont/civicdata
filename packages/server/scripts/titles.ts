// Writes src/titles.gen.ts: a plain-language title for each World Bank
// indicator, written by the agent's OpenAI model. Run it after the World Bank
// adds indicators, with OPENAI_API_KEY set (and OPENAI_MODEL to try another
// model):
//
//   pnpm --filter @civicdata/server run titles
//
// Every title is checked with `fits` against the official name; one that
// fails twice is left out, and the chart shows the official name instead.
import { writeFileSync } from "node:fs"

import type { CatalogEntry } from "@civicdata/domain"
import { OpenAiClient } from "@effect/ai-openai"
import { Array as Arr, Config, Effect, Layer, Option, Schema } from "effect"
import { LanguageModel } from "effect/ai"
import { FetchHttpClient } from "effect/http"

import { Cache } from "../src/Cache.ts"
import { about } from "../src/model.ts"
import { languageModel } from "../src/OpenAi.ts"
import { fits } from "../src/Titles.ts"
import { WorldBank } from "../src/WorldBank.ts"

const target = new URL("../src/titles.gen.ts", import.meta.url)

const perRequest = 40

const instructions = `You title charts of World Bank indicators for people who are not economists.

For each indicator you get its code, its official name and its definition. Write a title that says what the chart measures in everyday words.

- At most 60 characters, sentence case, no final period.
- Replace jargon and acronyms with plain words: "PPP" becomes "adjusted for living costs", "LCU" becomes "local currency", "per capita" becomes "per person". Keep a term people know, such as "GDP", "inflation" or "CO2".
- Keep what tells this indicator apart from its neighbors: the group (women, men, ages, urban or rural), the unit (%, US$, local currency) and whether prices are current or constant.
- Never write a number that is not in the official name. Keep years and age ranges as the name writes them.
- Use plain ASCII: straight quotes, no accented letters.`

const Titled = Schema.Struct({
  titles: Schema.Array(Schema.Struct({ indicator: Schema.String, title: Schema.String })),
})

// Titles for one request's indicators, without those that do not fit.
const titleSome = Effect.fn("titles.titleSome")(function* (entries: ReadonlyArray<CatalogEntry>) {
  const { value } = yield* LanguageModel.generateObject({
    objectName: "titles",
    schema: Titled,
    prompt: about(instructions, entries),
  })

  const names = new Map<string, string>(entries.map(({ indicator, name }) => [indicator, name]))

  return value.titles.flatMap(({ indicator, title }) => {
    const name = names.get(indicator)
    const trimmed = title.trim()

    return name !== undefined && fits(trimmed, name) ? [[indicator, trimmed] as const] : []
  })
})

const titleAll = (entries: ReadonlyArray<CatalogEntry>) =>
  Effect.forEach(Arr.chunksOf(entries, perRequest), titleSome, { concurrency: 4 }).pipe(
    Effect.map((batches) => batches.flat()),
  )

const program = Effect.gen(function* () {
  const entries = yield* (yield* WorldBank).indicators
  const first = yield* titleAll(entries)
  const done = new Set(first.map(([indicator]) => indicator))
  const second = yield* titleAll(entries.filter(({ indicator }) => !done.has(indicator)))

  const rows = [...first, ...second].toSorted(([a], [b]) => a.localeCompare(b))

  writeFileSync(
    target,
    [
      "// Generated by scripts/titles.ts. Do not edit.",
      "export const titles: ReadonlyMap<string, string> = new Map([",
      ...rows.map((row) => `  ${JSON.stringify(row)},`),
      "])",
      "",
    ].join("\n"),
  )

  yield* Effect.logInfo(`Titled ${rows.length} of ${entries.length} indicators`)
})

const model = Layer.unwrap(
  Effect.gen(function* () {
    const name = yield* Config.option(Config.String("OPENAI_MODEL"))

    return languageModel(Option.getOrUndefined(name))
  }),
)

await Effect.runPromise(
  program.pipe(
    Effect.provide(
      model.pipe(
        Layer.provideMerge(WorldBank.layer.pipe(Layer.provide(Cache.none))),
        Layer.provide(OpenAiClient.layerConfig({ apiKey: Config.Redacted("OPENAI_API_KEY") })),
        Layer.provide(FetchHttpClient.layer),
      ),
    ),
  ),
)
