import type { Country } from "@repo/domain"

interface Frame {
  readonly country: Country
  readonly id: string
  readonly centre: readonly [number, number]
  readonly land?: ReadonlyArray<string>
  readonly offshore?: ReadonlyArray<{
    readonly code: string
    readonly name: string
    readonly box: readonly [number, number, number, number]
  }>
  readonly context?: ReadonlyArray<{
    readonly name: string
    readonly codes: ReadonlyArray<string>
    readonly box?: readonly [number, number, number, number]
  }>
  readonly codes: ReadonlyArray<string>
  readonly insets: ReadonlyArray<{
    readonly code: string
    readonly detached: boolean
    readonly coverage?: "National" | "Context"
    readonly box?: readonly [number, number, number, number]
  }>
}

export type CountryMap = Frame &
  (
    | {
        readonly source: "NaturalEarth"
        readonly level: "division" | "region"
        readonly identifier?: "adm1_code"
        readonly members?: ReadonlyArray<string>
        readonly omit?: ReadonlyArray<string>
        readonly joins?: Readonly<Record<string, string>>
        readonly names?: Readonly<Record<string, string>>
      }
    | { readonly source: "ONS"; readonly country: "GBR" }
    | { readonly source: "Tailte"; readonly country: "IRL" }
    | { readonly source: "LandBoard"; readonly country: "EST" }
    | { readonly source: "Boundary" }
  )

