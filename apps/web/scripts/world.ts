// Writes src/explore/world.gen.ts: each country's outline, projected once so
// neither the browser nor the link-preview card projects at request time. Run
// with `pnpm --filter @civicdata/web run world`, then `pnpm format`, after
// changing the projection or the source map.
import { readFileSync, writeFileSync } from "node:fs"

import { countries } from "@civicdata/domain"
import { geoEqualEarth, type GeoPermissibleObjects, geoPath } from "d3-geo"
import type { Feature, Geometry } from "geojson"
import { feature } from "topojson-client"
import type { GeometryCollection, Topology } from "topojson-specification"

const read = (file: string) => readFileSync(new URL(import.meta.resolve(file)), "utf8")

// Natural Earth 1:110m, keyed by ISO 3166-1 numeric code.
const topology: Topology<{ countries: GeometryCollection<{ name: string }> }> = JSON.parse(
  read("world-atlas/countries-110m.json"),
)

// [alpha-2, alpha-3, numeric] for every ISO 3166-1 country.
const codes: ReadonlyArray<readonly [string, string, string]> = JSON.parse(
  read("i18n-iso-countries/codes.json"),
)

const alpha3 = new Map(codes.map(([, three, numeric]) => [numeric, three]))
const economies = new Set<string>(countries.map((country) => country.code))

// Kosovo has no ISO code; the World Bank calls it XKX.
const codeOf = (place: Feature<Geometry, { name: string }>) =>
  place.properties.name === "Kosovo" ? "XKX" : alpha3.get(`${place.id}`)

const width = 1000
const sphere: GeoPermissibleObjects = { type: "Sphere" }
const projection = geoEqualEarth().fitWidth(width, sphere)
const [[, top], [, bottom]] = geoPath(projection).bounds(sphere)
const height = Math.ceil(bottom - top)

// The projected rings of one outline, in whole units, with repeated points
// dropped. d3 clips them at the edge of the map, e.g. Russia and Fiji.
const ringsOf = (area: GeoPermissibleObjects) => {
  const rings: Array<Array<readonly [number, number]>> = []

  const add = (x: number, y: number) => {
    const point = [Math.round(x), Math.round(y - top)] as const
    const ring = rings.at(-1)
    const last = ring?.at(-1)

    if (ring !== undefined && (last === undefined || last[0] !== point[0] || last[1] !== point[1]))
      ring.push(point)
  }

  geoPath(projection, {
    beginPath: () => undefined,
    moveTo: (x, y) => {
      rings.push([])
      add(x, y)
    },
    lineTo: add,
    closePath: () => undefined,
    arc: () => undefined,
  })(area)

  return rings.filter((ring) => ring.length >= 3)
}

// Each ring as whole numbers: its first point, then the step to each next one.
const stepsOf = (rings: ReadonlyArray<ReadonlyArray<readonly [number, number]>>) =>
  rings.map((ring) =>
    ring.flatMap(([x, y], index) => {
      const previous = ring[index - 1]

      return previous === undefined ? [x, y] : [x - previous[0], y - previous[1]]
    }),
  )

const outlines = feature(topology, topology.objects.countries).features.flatMap((place) => {
  const code = codeOf(place)

  return code === undefined || !economies.has(code) ? [] : [[code, stepsOf(ringsOf(place))]]
})

writeFileSync(
  new URL("../src/explore/world.gen.ts", import.meta.url),
  `// Generated by scripts/world.ts from Natural Earth 1:110m country outlines
// (public domain, https://www.naturalearthdata.com) via world-atlas. Do not edit.
import type { Country } from "@civicdata/domain"

// The world in the Equal Earth projection, \`width\` by \`height\` units.
export const width = ${width}
export const height = ${height}

// Each World Bank economy large enough to draw at this scale, as rings: the
// first point of each, then the step to each next point, all in whole units.
export const outlines: Readonly<Partial<Record<Country, ReadonlyArray<ReadonlyArray<number>>>>> = ${JSON.stringify(Object.fromEntries(outlines))}
`,
)
